"""app/schemas/api.py

THE CONTRACT BETWEEN THE ORCHESTRATOR AND THE REACT UI.
(frontend/src/types.ts mirrors these models by hand -- keep them in sync.)

Design rule: the UI never has to guess. The number to display always comes from
`predictions[i].predicted_final_score`, which is filled in by CODE from the MCP tool
result -- never parsed out of the LLM's prose.
"""
from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field, field_validator

MAX_MESSAGE_CHARS = 1000


class ChatRequest(BaseModel):
    message: str = Field(..., description="The user's question in natural language")
    conversation_id: str | None = Field(
        default=None, pattern=r"^[A-Za-z0-9_-]{8,64}$",
        description="Omit to start a new conversation; send the returned id to continue it",
    )

    @field_validator("message")
    @classmethod
    def _check_message(cls, v: str) -> str:
        v = v.strip()
        if not v:
            raise ValueError("message must not be empty")
        if len(v) > MAX_MESSAGE_CHARS:
            raise ValueError(f"message must be at most {MAX_MESSAGE_CHARS} characters")
        return v


class PredictionResult(BaseModel):
    """One real prediction made by the ML model (via MCP -> ML API)."""

    label: str = Field(description="'Student' for one prediction, 'Profile 1', 'Profile 2'... when several")
    predicted_final_score: float = Field(description="Exactly the number returned by the ML API")
    features: dict = Field(description="The validated input values that were sent to the model")
    model_version: str | None = None
    ml_request_id: str | None = Field(default=None, description="Request id generated by the ML API (log correlation)")


class ToolCallRecord(BaseModel):
    tool: str
    status: Literal["ok", "error", "rejected"] = Field(
        description="ok = tool ran; error = tool/ML API failed; rejected = the orchestrator refused to call it (missing/unclear inputs)"
    )
    label: str | None = None
    error_code: str | None = None
    latency_ms: float | None = None


class FieldProblem(BaseModel):
    field: str
    problem: str


class ProfileClarification(BaseModel):
    label: str
    missing_fields: list[str] = Field(default_factory=list)
    problems: list[FieldProblem] = Field(default_factory=list)
    understood_values: dict = Field(default_factory=dict, description="Values that were clearly stated and are valid so far")


class ErrorInfo(BaseModel):
    code: str
    message: str
    retryable: bool | None = None
    details: list[str] = Field(default_factory=list)


class ProviderInfo(BaseModel):
    name: str
    model: str


class ChatResponse(BaseModel):
    trace_id: str
    conversation_id: str
    kind: Literal["prediction", "clarification", "information", "text", "error"]
    assistant_message: str = Field(description="Natural-language reply. Explanation only -- the model output is in `predictions`")
    predictions: list[PredictionResult] = Field(default_factory=list)
    clarification: list[ProfileClarification] | None = None
    model_information: dict | None = Field(default=None, description="Present when the user asked about the model; copied from the tool result")
    tool_calls: list[ToolCallRecord] = Field(default_factory=list)
    error: ErrorInfo | None = None
    notices: list[str] = Field(default_factory=list, description="Non-fatal remarks, e.g. 'assistant text replaced by a safe summary'")
    provider: ProviderInfo
    latency_ms: float


class ErrorResponse(BaseModel):
    """Returned with a non-2xx status when the request itself could not be served."""

    trace_id: str
    error: ErrorInfo


class HealthResponse(BaseModel):
    status: Literal["ok"]
    service: str = "orchestrator"
    provider: ProviderInfo
    llm_configured: bool
    llm_note: str | None = None
