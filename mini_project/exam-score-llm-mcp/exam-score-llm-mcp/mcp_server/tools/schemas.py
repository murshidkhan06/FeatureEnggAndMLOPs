"""mcp_server/tools/schemas.py

THE INPUT CONTRACT OF THE `predict_exam_score` TOOL.

These fields are copied from the EXISTING ML API's `StudentInput` model
(exam-score-mlops/api/main.py). They are not invented here. A test
(tests/integration/test_contract.py) compares them against the live ML API's
/openapi.json, so if the ML team changes their API, our tests fail loudly instead of the
chatbot silently sending wrong data.

NOTE what is NOT here: no scaling, no encoding, no imputation, no feature creation.
The fitted scikit-learn Pipeline inside the ML API does all of that. We only validate
that the *raw* values are sensible before sending them.
"""
from __future__ import annotations

import re
from datetime import date
from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator

# Each alias carries its own validation rules AND its description. FastMCP turns the
# description into the JSON-Schema the LLM sees, so the descriptions below are the
# "documentation" the model reads when deciding how to fill each argument.
StudyHours = Annotated[float, Field(ge=0, le=40, description="Study hours per WEEK (not per day). Range 0-40.")]
AttendancePct = Annotated[float, Field(ge=0, le=100, description="Class attendance percentage, 0-100.")]
MockScore = Annotated[float, Field(ge=0, le=100, description="Mock test score out of 100.")]
IncomeBracket = Annotated[Literal["Low", "Medium", "High"], Field(description="Family income bracket: Low, Medium or High.")]
City = Annotated[str, Field(min_length=1, max_length=50, description="City name, e.g. Pune, Delhi, Mumbai, Bengaluru.")]
EnrollmentDate = Annotated[str, Field(description="Enrollment date in YYYY-MM-DD format.")]
ShoeSize = Annotated[float, Field(gt=0, le=25, description="Shoe size. (The model ignores this, but the ML API requires it.)")]
LuckyNumber = Annotated[int, Field(ge=0, le=1000, description="Lucky number. (The model ignores this, but the ML API requires it.)")]

_CITY_RE = re.compile(r"^[A-Za-z][A-Za-z .'\-]*$")
_DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")


class StudentFeatures(BaseModel):
    """The 10 raw fields the ML API's /predict endpoint requires. All are required;
    the ML API defines no defaults, so neither do we."""

    model_config = ConfigDict(extra="forbid")

    study_hours: StudyHours
    attendance_pct: AttendancePct
    mock_test_1: MockScore
    mock_test_2: MockScore
    mock_test_3: MockScore
    income_bracket: IncomeBracket
    city: City
    enrollment_date: EnrollmentDate
    shoe_size: ShoeSize
    lucky_number: LuckyNumber

    @field_validator("city")
    @classmethod
    def _city_is_a_name(cls, v: str) -> str:
        v = v.strip()
        if not _CITY_RE.match(v):
            raise ValueError("city must contain only letters, spaces, dots, apostrophes or hyphens")
        return v

    @field_validator("enrollment_date")
    @classmethod
    def _date_is_real(cls, v: str) -> str:
        v = v.strip()
        if not _DATE_RE.match(v):
            raise ValueError("enrollment_date must be in YYYY-MM-DD format")
        try:
            date.fromisoformat(v)  # rejects things like 2025-02-31
        except ValueError as exc:
            raise ValueError(f"enrollment_date is not a real calendar date: {v}") from exc
        return v


FEATURE_NAMES: list[str] = list(StudentFeatures.model_fields.keys())


# ---- What the tool returns ---------------------------------------------------------------

class ToolError(BaseModel):
    code: str = Field(description="Stable machine-readable error code, e.g. ML_API_UNAVAILABLE")
    message: str = Field(description="Human-readable explanation, safe to show to users")
    retryable: bool = Field(description="True if trying again later might work")
    details: list[str] = Field(default_factory=list, description="Optional short details, e.g. which fields were rejected")


class PredictionToolResult(BaseModel):
    ok: bool
    predicted_final_score: float | None = Field(default=None, description="The ML model's prediction, exactly as returned by the ML API")
    model_version: str | None = Field(default=None, description="Model version string reported by the ML API")
    ml_request_id: str | None = Field(default=None, description="Request ID generated by the ML API (for log correlation)")
    features_used: dict | None = Field(default=None, description="The validated input values sent to the ML API")
    error: ToolError | None = None
