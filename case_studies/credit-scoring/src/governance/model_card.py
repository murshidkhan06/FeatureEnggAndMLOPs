"""Generate the MODEL REVIEW PACK (a model card for regulators / validators) from the registry + metrics + audits.

WHY generate it?  A hand-written document goes stale the day the model is retrained.  This script rebuilds
reports/model_review_pack.md from the SAME sources the pipeline uses (feature registry, champion artifact,
evaluation, fairness audit), so what reviewers read is what is deployed.  Sign-offs are NOT automated: the checklist
at the end stays PENDING until a human records an approval.

Run:  python -m src.governance.model_card
"""
from __future__ import annotations

import json
import subprocess
from datetime import datetime, timezone

import pandas as pd
import yaml

from src import project as P
from src.common.artifact import load_artifact
from src.common.params import load_params
from src.common.paths import CHAMPION_PATH, CONFIGS, DATA_RAW, REPORTS, ROOT
from src.features.registry import load_registry
from src.governance.fairness_audit import run_audit
from src.models.evaluate import evaluate
from src.models.reason_codes import standardized_coefficients


def dvc_lineage() -> str:
    """Actual DVC md5 of the raw data if `dvc repro` has been run (dvc.lock), else an explicit placeholder."""
    lock = ROOT / "dvc.lock"
    if lock.exists():
        try:
            outs = yaml.safe_load(lock.read_text())["stages"]["make_data"]["outs"]
            return ", ".join(f"{o['path']} md5={o['md5']}" for o in outs)
        except Exception:                                                    # noqa: BLE001
            pass
    return "DVC md5 not available yet - run `dvc repro` (placeholder: <md5 of data/raw after dvc repro>)"


def git_commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True, timeout=5).stdout.strip() or "n/a (not a git repo)"
    except Exception:                                                        # noqa: BLE001
        return "n/a"


def md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(v) for v in r.tolist()) + " |")
    return "\n".join(lines)


def build_card() -> str:
    prm = load_params()
    art = load_artifact(CHAMPION_PATH)
    reg = load_registry()
    feats = art["input_columns"]
    ev = evaluate(art)
    au = run_audit(art)
    sel = pd.read_csv(REPORTS / "feature_selection.csv") if (REPORTS / "feature_selection.csv").exists() else None
    age_exp = json.loads((REPORTS / "age_experiment.json").read_text()) if (REPORTS / "age_experiment.json").exists() else None
    fair = json.loads((REPORTS / "fairness_report.json").read_text()) if (REPORTS / "fairness_report.json").exists() else None
    raw_rows = sum(1 for _ in open(DATA_RAW / "applications.csv", encoding="utf-8")) - 1 if (DATA_RAW / "applications.csv").exists() else "n/a"
    m = ev["metrics"]
    L = []
    L.append(f"# Model Review Pack - {P.TITLE}\n")
    L.append(f"*Generated {datetime.now(timezone.utc).isoformat(timespec='seconds')} by `python -m src.governance.model_card`.  "
             "Educational project: data is synthetic and every sign-off below is a placeholder, not a real approval.*\n")
    L.append(f"| Item | Value |\n|---|---|\n| Model | {P.MODEL_NAME} {art['version']} ({art['extra'].get('model_family')}) |\n| Trained at | {art['trained_at']} |\n"
             f"| Git commit | {git_commit()} |\n| Status | DRAFT - pending human sign-off |\n")
    L.append("## 1. Model purpose and scope\n"
             "* **Decision supported**: approve / refer / decline an unsecured personal loan at application time.\n"
             "* **Output**: probability of default within 12 months of disbursal (PD), risk band and reason codes.\n"
             f"* **Bands**: LOW PD < {P.REFER_CUTOFF} -> APPROVE; MEDIUM {P.REFER_CUTOFF}-{P.DECLINE_CUTOFF} -> REFER_TO_UNDERWRITER (human); HIGH >= {P.DECLINE_CUTOFF} -> DECLINE.\n"
             "* **Out of scope**: secured loans, business loans, collections strategy, pricing.  Not to be used on populations unlike the training data.\n")
    L.append("## 2. Data lineage\n"
             f"* Source: synthetic applications generated by `src/data/make_dataset.py` (seed {prm['data']['seed']}), {raw_rows} rows, 2022-01-01 .. 2023-12-31.\n"
             f"* Split: time-based {prm['split']['train_frac']:.0%}/{prm['split']['valid_frac']:.0%}/{prm['split']['test_frac']:.0%}; repeat applicants removed across parts.\n"
             f"* Training window: {art['extra'].get('train_period')}, {art['extra'].get('n_train')} applications.\n"
             f"* Data versioning: {dvc_lineage()}\n")
    L.append("## 3. Feature approval table (features used by the model)\n")
    rows = [dict(feature=f, owner=reg[f]["owner"], source=reg[f]["source"], available_at_prediction=reg[f]["prediction_time_availability"][:40],
                 status=reg[f]["status"], version=reg[f]["version"], sensitivity=reg[f]["sensitivity"]) for f in feats]
    L.append(md_table(pd.DataFrame(rows)) + "\n")
    L.append("## 4. Rejected features and reasons\n")
    rej = [dict(feature=n, category=r["decision_category"], reason=r["reason"][:170]) for n, r in reg.items() if r["status"] == "Rejected"]
    L.append(md_table(pd.DataFrame(rej)) + "\n")
    if sel is not None:
        stat_rej = sel[sel.decision.str.startswith("REJECTED") & sel.feature.isin([n for n, r in reg.items() if r["status"] == "Approved"])]
        L.append("Approved but not selected by the statistical steps:\n")
        L.append(md_table(stat_rej[["feature", "decision"]]) + "\n")
    L.append("## 5. Performance (TEST = newest 15% of applications, untouched during development)\n")
    L.append(md_table(pd.DataFrame(m).T.reset_index().rename(columns={"index": "split"}).round(4)) + "\n")
    cmpd = pd.DataFrame(ev["comparison_test"]).T.reset_index().rename(columns={"index": "model"})[["model", "roc_auc", "gini", "ks_stat", "pr_auc", "recall_at_80_approval"]].round(4)
    L.append("Comparison with the baseline and the boosting benchmark (test):\n\n" + md_table(cmpd) + "\n")
    L.append("Risk bands on test:\n\n" + md_table(pd.DataFrame(ev["bands_test"])) + "\n")
    b = ev["business_test"]
    L.append(f"Business view at {b['approval_rate']:.0%} approval rate (assumptions: loss given default {prm['business']['loss_given_default']:.0%}, "
             f"margin {prm['business']['margin_on_good_loan']:.0%}): loss avoided INR {b['loss_avoided']:,}, margin lost INR {b['margin_lost']:,}, net INR {b['net_benefit']:,}.\n")
    L.append("## 6. Stability\n"
             f"* KS test of score distributions train vs test: D = {ev['score_stability_ks_train_vs_test']['D']}, p = {ev['score_stability_ks_train_vs_test']['p_value']:.3g} (D < 0.10 = stable).\n"
             "* Calibration (test deciles): see `reports/evaluation.json`.  Mean predicted PD vs observed default rate per decile is shown in docs/sample_outputs/06_evaluation.txt.\n")
    L.append("## 7. Fairness (gender and age are audit-only, never model inputs)\n")
    L.append(md_table(au["gender"].round(4)) + "\n")
    s = au["gender_summary"]
    L.append(f"* Adverse impact ratio (gender) = **{s['air']}** (rule of thumb >= {prm['fairness']['min_adverse_impact_ratio']}); equal-opportunity gap = {s['eo_gap']}; "
             f"denial-rate ratio = {au['decline_rate_ratio']}; auto-approval AIR = {au['auto_approval_air']}.\n")
    L.append("Age bands:\n\n" + md_table(au["age"].round(4)) + f"\n\n* Age-band adverse impact ratio = {au['age_summary']['air']} (monitored; age is excluded as a POLICY decision).\n")
    if fair:
        L.append("Before / after removing proxies (same decline rate):\n\n" + md_table(pd.DataFrame(fair["variants"])) + "\n")
    if age_exp:
        g = age_exp["auc_gain"]
        L.append(f"Age experiment: AUC gain from adding age {g['mean']:+.4f} (95% interval [{g['lo']:+.4f}, {g['hi']:+.4f}]).  Decision: {age_exp['decision']} - owned by Compliance; laws differ by country.\n")
    L.append("## 8. Explainability\n")
    sc = standardized_coefficients(art["pipeline"], feats)
    L.append("Standardized coefficients (log-odds per +1 std; positive = riskier):\n\n" + md_table(sc[["feature", "encoded", "coef"]].round(3)) + "\n")
    L.append("Per-applicant reason codes: the API returns the top-3 adverse factors (coefficient x standardized value).  "
             "Importance describes the MODEL, not causes (association, not causation).\n")
    L.append("## 9. Limitations\n"
             "* Synthetic data: coefficients and rates are illustrative, not a real bank's risk.\n"
             "* Selection bias: in real life we only observe outcomes for approved applicants (no reject inference here).\n"
             "* `emi_estimate` uses an assumed 14% rate, not the rate actually offered (which would be leakage).\n"
             f"* ~{int(m['test']['n'] * m['test']['default_rate'])} defaulters in the test set: AUC differences of +-0.02 are within noise.\n"
             "* Labels arrive 12 months late; monitoring relies on input drift and the data-quality ladder until then.\n"
             "* Fairness numbers are evidence on two attributes only; they are not a legal compliance opinion.\n")
    L.append("## 10. Monitoring plan\n"
             f"* Drift features (KS test, alpha 0.05, practical threshold D >= 0.10): {', '.join(P.DRIFT_FEATURES)}.\n"
             "* Data quality (nulls, ranges, unit sanity) is checked first on every batch; Prometheus alerts on 422 spikes, approval-rate jumps and drift flags.\n"
             "* When 12-month labels arrive: AUC / KS / calibration on real outcomes; retrain only through `src/models/retrain.py` (champion / challenger + human approval).\n"
             "* Fairness audit repeated on every retrain and every quarter.\n")
    L.append("## 11. Sign-off checklist\n")
    so = pd.DataFrame([
        dict(step="Development - automated review gate", owner="Model owner", status="Run `python -m src.governance.review_gate`", date="-"),
        dict(step="Independent validation", owner="Validation team", status="PENDING (human)", date="-"),
        dict(step="Compliance / fairness review", owner="Compliance", status="PENDING (human)", date="-"),
        dict(step="Model risk committee approval", owner="Risk committee", status="PENDING (human)", date="-"),
    ])
    L.append(md_table(so) + "\n")
    return "\n".join(L)


def main() -> None:
    REPORTS.mkdir(exist_ok=True)
    text = build_card()
    (REPORTS / "model_review_pack.md").write_text(text, encoding="utf-8")
    print(f"written {REPORTS / 'model_review_pack.md'}  ({len(text.splitlines())} lines, {len(text)} characters)")
    print("sections:", [ln[3:] for ln in text.splitlines() if ln.startswith("## ")])


if __name__ == "__main__":
    main()
